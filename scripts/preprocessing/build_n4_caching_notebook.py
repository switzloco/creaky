    "def process_plane(s_dir: str, num_slices: int, target_size: Tuple[int, int]) -> np.ndarray:\n",
    "    dcm_files = get_sorted_files(s_dir)\n",
    "    h, w = target_size\n",
    "    if not dcm_files:\n",
    "        return np.zeros((num_slices, h, w), dtype=np.uint8)\n",
